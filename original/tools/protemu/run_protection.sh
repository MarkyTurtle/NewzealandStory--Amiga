#!/bin/sh
# Run the track 0 protection loader (Rob Northen Copylock, at $60000) in protemu until it enters
# its decrypted payload, and write:
#   bin/protection_payload_60000.bin  the payload as it starts at $60000 ($424 bytes)
#   disk/files/t000_boot_stage2.bin   the second-stage bootblock inside it (1024 bytes)
#   nzs_protection_run.lst            every distinct instruction executed, decrypted (by first use)
#
# The Copylock disk check (which times reads of the long track 1) is not emulated: at its call
# ($604D0) the run goes straight to the check's exit ($60868) with d0 = $F974DB7D, the key the
# track 90 loader needs (key - $F974D77D = $400). The track 0 copy does not use its key: the
# payload is decrypted with the code checksums the layers accumulate.
set -e
cd "$(dirname "$0")/../.."
[ -x tools/protemu/protemu ] || sh tools/protemu/build.sh
tmp=$(mktemp -d)
tools/protemu/protemu disk/files/t000_protection_loader.bin 0x60000 0x60000 \
    -o 2 -T 0x600CA -j 0x604D0 -J 0x60868 -k 0xF974DB7D -K 0x60868 -r a0=0x20000 \
    -S 0x60000 -n 2 -L "$tmp/run.lst" -d "$tmp/payload.bin" 0x60000 0x424
cp "$tmp/payload.bin" bin/protection_payload_60000.bin
dd if="$tmp/payload.bin" of=disk/files/t000_boot_stage2.bin bs=1 skip=$((0x24)) count=1024 2>/dev/null
{
  echo "; The New Zealand Story - track 0 protection loader as executed in protemu (tools/protemu)"
  echo "; Generated by tools/protemu/run_protection.sh: each distinct instruction once, in the order"
  echo "; first executed, as the CPU saw it (decrypted). T = traced (decrypted by the trace handler)."
  echo "; The trace handler ($601F6-$60220) is listed once; the disk check ($604D0) is skipped."
  echo ";"
  echo "; step      pc     bytes                  T  instruction"
  sort -n "$tmp/run.lst" | awk -F'\t' '{printf "%9s  %6s  %-20s  %1s  %s\n", $1, $2, $3, $4, $5}'
} > nzs_protection_run.lst
rm -r "$tmp"
sha1sum bin/protection_payload_60000.bin disk/files/t000_boot_stage2.bin
