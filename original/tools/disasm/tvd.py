"""Decrypt Rob Northen's trace-vector-encrypted code (Copylock) and list it.

  python3 tools/disasm/tvd.py            -> nzs_protection_tvd.lst (track 0 loader at $60000)
                                            nzs_loader_tvd.lst     (track 90 loader at $76000)

The disk has the same scheme twice: the protection loader read from track 0 by the bootblock
(runs at $60000) and the game loader on track 90 (its block at $76000). In both:

  * the code saves the registers and executes ILLEGAL with the illegal vector pointing at the
    next stage, which tries MOVEC CACR (68020+: the cache off; on a 68000 itself illegal), saves
    vectors $8-$27, and executes ILLEGAL again into the "enter" handler;
  * the enter handler (supervisor) sets the trace vector and the privilege-violation vector,
    steps the return address past the ILLEGAL, toggles the trace bit in the stacked SR
    (bchg #7) and decrypts the first instruction before its RTE;
  * the trace handler, after every instruction: puts back the encrypted long it decrypted last
    time, then for the next instruction at A (the stacked PC)
        long[A] ^= swap(~long[A-4])      (long[A-4] read while still encrypted)
    Only the first long of an instruction is decrypted; any further words are used as they are;
  * ILLEGAL inside the encrypted code goes through the enter handler again, whose bchg #7 turns
    tracing off: the code after it runs in the clear (the timing-critical disk reads) until the
    next ILLEGAL turns it back on.

Because the handler re-encrypts before decrypting, an instruction's plain text depends only on
the original image and its own address, so the code is decrypted here statically by following
the flow from the first instruction. Each listing shows every instruction as the CPU sees it.
"""
import os, re, sys
import capstone

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
md = capstone.Cs(capstone.CS_ARCH_M68K, capstone.CS_MODE_BIG_ENDIAN | capstone.CS_MODE_M68K_000)
HEX = re.compile(r'\$([0-9a-f]+)')


class TVD:
    def __init__(self, image, base, start, end):
        self.enc, self.base, self.start, self.end = image, base, start, end

    def long_at(self, a):
        return int.from_bytes(self.enc[a - self.base:a - self.base + 4], 'big')

    def decrypt_at(self, a):
        """The bytes the CPU sees at a when the trace handler has prepared instruction a."""
        k = (~self.long_at(a - 4)) & 0xFFFFFFFF
        k = ((k << 16) | (k >> 16)) & 0xFFFFFFFF
        first = (self.long_at(a) ^ k).to_bytes(4, 'big')
        return first + self.enc[a - self.base + 4:a - self.base + 10]

    def walk(self):
        ins, work = {}, [(self.start, True)]
        while work:
            a, enc = work.pop()
            while self.base <= a < self.end and a not in ins:
                b = self.decrypt_at(a) if enc else self.enc[a - self.base:a - self.base + 10]
                if b[:2] in (b'\x4e\x7a', b'\x4e\x7b') and b[2:4] == b'\x00\x02':   # 68010+: capstone's 68000 mode can't show it
                    txt = 'cacr, d0' if b[1] == 0x7a else 'd0, cacr'
                    ins[a] = (4, 'movec', txt, b[:4].hex(), '68020+ only: skipped on a 68000' + ('' if enc else '; plain (runs untraced)'))
                    a += 4
                    continue
                i = next(md.disasm(b, a), None)
                if i is None:
                    ins[a] = (2, 'dc.w', f'${b[0]:02X}{b[1]:02X}', b[:2].hex(), 'undecodable')
                    break
                m, op = i.mnemonic, i.op_str
                ins[a] = (i.size, m, op, i.bytes.hex(), '' if enc else 'plain (runs untraced)')
                base = m.split('.')[0]
                if base in ('bra', 'bsr') or base.startswith('db') or (base.startswith('b') and base not in ('btst', 'bchg', 'bclr', 'bset')):
                    work.append((int(HEX.findall(op)[-1], 16), enc))
                if base in ('jmp', 'jsr') and re.match(r'^\$[0-9a-f]+(\.[wl])?$', op):
                    work.append((int(HEX.findall(op)[0], 16), enc))
                if m == 'illegal':
                    ins[a] = ins[a][:4] + ('trace ' + ('off: the code after this runs in the clear' if enc else 'back on'),)
                    enc = not enc
                elif base in ('bra', 'jmp', 'rts', 'rte'):
                    break
                a += i.size
        return ins

    def listing(self, title, out):
        ins = self.walk()
        targets = {int(x, 16) for (_s, mm, o, _h, _n) in ins.values()
                   if mm.split('.')[0].startswith('b') or mm.startswith('db') for x in HEX.findall(o)}
        L = [f'; The New Zealand Story - {title}: the trace-vector-encrypted code, decrypted',
             '; Generated by tools/disasm/tvd.py (see its header for how the decryption works).',
             '; Each instruction is shown as the CPU sees it at that moment; the bytes in the source',
             '; stay encrypted. This listing is for reading: it is not meant to be assembled.',
             '; address  bytes (decrypted)      instruction', '']
        for a in sorted(ins):
            sz, m, op, hx, note = ins[a]
            if a in targets:
                L.append(f'L{a:05X}:')
            L.append(f'  {a:05X}  {hx:<20}  {m:<8} {op}' + (f'   ; {note}' if note else ''))
        open(os.path.join(ROOT, out), 'w').write('\n'.join(L) + '\n')
        print(f'{title}: {len(ins)} instructions decrypted -> {out}')
        return ins


BLOCKS = [   # title, file, file offset of the run base, run base, first encrypted instruction, end, listing
    ('track 0 protection loader', 'disk/files/t000_protection_loader.bin', 0, 0x60000, 0x6013C, 0x603B0,
     'nzs_protection_tvd.lst'),
    ('track 90 game loader', 'disk/files/t090_game_loader.bin', 4, 0x76000, 0x76186, 0x76668,
     'nzs_loader_tvd.lst'),
]


def block(n):
    t, f, off, base, start, end, out = BLOCKS[n]
    raw = open(os.path.join(ROOT, f), 'rb').read()
    return TVD(raw[off:], base, start, end), t, out


def main():
    for n in range(len(BLOCKS)):
        tv, t, out = block(n)
        tv.listing(t, out)


if __name__ == '__main__':
    main()
