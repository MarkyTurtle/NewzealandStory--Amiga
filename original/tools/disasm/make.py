"""Generate a source from its config, assemble it with vasm and check it against the original.

  python3 tools/disasm/make.py [main] [loader] [boot] [boot2]      (default: all)

Kept for the record: the sources in original/ (nzs_main.s, nzs_loader.s, nzs_boot.s,
nzs_boot2.s, nzs_hw.i, nzs_equates.i) were made by this from the configs and have been edited by
hand since October 2026 - they are the source now, and this never writes over them. It writes
what the configs give to tools/disasm/regen/ (not kept in git) and checks that against the
original binaries, for comparing with the hand-edited sources if that is ever useful.
"""
import hashlib, importlib, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
OUT = os.path.join(HERE, 'regen')         # where the generated sources go (never ROOT)
sys.path.insert(0, HERE)
import core

PROGRAMS = {            # config module, source written, original binary (file, start, length)
    'main': ('main_cfg', 'nzs_main.s', ('bin/main.bin', 0, None)),
    'loader': ('loader_cfg', 'nzs_loader.s', ('disk/files/t090_game_loader.bin', 0, None)),
    'boot': ('boot_cfg', 'nzs_boot.s', ('disk/files/t000_bootblock.bin', 0, None)),
    'boot2': ('boot2_cfg', 'nzs_boot2.s', ('disk/files/t000_boot_stage2.bin', 0, None)),
}


def assemble(src, out):
    r = subprocess.run(['vasmm68k_mot', '-Fbin', '-m68000', '-no-opt', '-quiet', '-o', out, src],
                       capture_output=True, text=True, cwd=OUT)
    if r.returncode:
        print(r.stdout + r.stderr)
        raise SystemExit(f'{src}: assembly failed')


def write_hw():
    """nzs_hw.i: custom chip registers (offsets from CUSTOM), the CIAs, the exception vectors."""
    from hw import CUSTOM, CIAA, CIAB
    L = ['; Amiga hardware: custom chip registers (offsets from CUSTOM), CIA registers, exception vectors',
         '; Generated by tools/disasm/make.py (tools/disasm/hw.py).', '',
         'CUSTOM\t\tequ\t$DFF000\t\t; custom chip base', '']
    L += [f'{n:<12}\tequ\t${o:03X}' for o, n in sorted(CUSTOM.items())]
    L += ['', '; CIA-A (registers at $BFE001, odd addresses)']
    L += [f'{n:<12}\tequ\t${0xBFE000 + o:06X}' for o, n in sorted(CIAA.items())]
    L += ['', '; CIA-B (registers at $BFD000, even addresses)']
    L += [f'{n:<12}\tequ\t${0xBFD000 + o:06X}' for o, n in sorted(CIAB.items())]
    L += ['', '; 68000 exception vectors']
    L += [f'V_{n:<16}\tequ\t${a:02X}' for a, n in sorted(core.VECTOR_NAMES.items())]
    open(os.path.join(OUT, 'nzs_hw.i'), 'w').write('\n'.join(L) + '\n')


def main():
    os.makedirs(OUT, exist_ok=True)
    write_hw()
    names = sys.argv[1:] or list(PROGRAMS)
    ok = True
    for n in names:
        mod, src, (orig, start, length) = PROGRAMS[n]
        print(f'{n}: tools/disasm/regen/{src} (the source kept is original/{src}, edited by hand)')
        cfg = importlib.import_module(mod)
        core.build(cfg, os.path.join(OUT, src))
        out = os.path.join(HERE, f'_{n}.bin')
        assemble(src, out)
        got = open(out, 'rb').read()
        want = open(os.path.join(ROOT, orig), 'rb').read()[start:None if length is None else start + length]
        os.remove(out)
        if got == want:
            print(f'  reassembles byte-identical to {orig} (sha1 {hashlib.sha1(got).hexdigest()})')
        else:
            ok = False
            d = next((i for i in range(min(len(got), len(want))) if got[i] != want[i]), min(len(got), len(want)))
            print(f'  MISMATCH with {orig}: sizes {len(got)}/{len(want)}, first difference at file offset ${d:X}')
    sys.exit(0 if ok else 1)


if __name__ == '__main__':
    main()
